// Map a child's age to the highest prompt level they should see (notes 14/7 · mục 2.6).
export const promptLevelForAge = (age?: number): PromptLevel => {
  if (typeof age !== 'number' || !Number.isFinite(age) || age <= 0) return 3;
  if (age <= 6) return 1;
  if (age <= 8) return 2;
  return 3;
};

// Prompts a child of the given age should see: those at or below their level.
// Falls back to the full list when a topic has no prompt at/under that level.
export const promptsForAge = (prompts: TopicPrompt[], age?: number): TopicPrompt[] => {
  const maxLevel = promptLevelForAge(age);
  const filtered = prompts.filter((prompt) => prompt.level <= maxLevel);
  return filtered.length > 0 ? filtered : prompts;
};
